/* -------------------------------------------------------------------------- */
/* Argument parsing helpers                                                   */
/* -------------------------------------------------------------------------- */

type ArgValue = string | boolean | (string | boolean)[] | undefined;
type ArgValues = Record<string, ArgValue>;

function asString(values: ArgValues, key: string): string | undefined {
  const value = values[key];
  return typeof value === "string" ? value : undefined;
}

function asStrings(values: ArgValues, key: string): string[] {
  const value = values[key];
  if (typeof value === "string") {
    return [value];
  }
  if (Array.isArray(value)) {
    return value.filter((entry): entry is string => typeof entry === "string");
  }
  return [];
}

function asBoolean(values: ArgValues, key: string): boolean {
  return values[key] === true;
}

function parseProfiles(values: ArgValues): TargetProfile[] | undefined {
  const raw = asStrings(values, "profile");
  if (raw.length === 0) {
    return undefined;
  }
  const profiles: TargetProfile[] = [];
  for (const entry of raw) {
    const candidate = entry.trim().toLowerCase();
    if (!isTargetProfile(candidate)) {
      throw new CtxSyncError(
        `Unknown profile "${entry}". Choose from: ${TARGET_PROFILES.join(", ")}.`,
        { code: "cli.profile", exitCode: 2 },
      );
    }
    if (!profiles.includes(candidate)) {
      profiles.push(candidate);
    }
  }
  return profiles;
}

function parseFailOn(values: ArgValues): FailOn {
  const raw = asString(values, "fail-on") ?? "warning";
  if (raw === "warning" || raw === "critical" || raw === "never") {
    return raw;
  }
  throw new CtxSyncError(
    `--fail-on must be warning, critical, or never (got "${raw}").`,
    { code: "cli.fail-on", exitCode: 2 },
  );
}

function parseBudget(raw: string | undefined, label: string): number | undefined {
  if (raw === undefined) {
    return undefined;
  }
  if (!/^\d+$/.test(raw)) {
    throw new CtxSyncError(
      `${label} must be a non-negative integer (0 disables the limit).`,
      { code: "cli.budget", exitCode: 2 },
    );
  }
  const value = Number(raw);
  if (!Number.isSafeInteger(value)) {
    throw new CtxSyncError(`${label} is too large.`, {
      code: "cli.budget",
      exitCode: 2,
    });
  }
  return value;
}

function parseCommandArgs(
  args: string[],
  options: NonNullable<ParseArgsConfig["options"]>,
): ArgValues {
  try {
    const parsed = parseArgs({
      args,
      options,
      allowPositionals: false,
      strict: true,
    });
    return parsed.values as ArgValues;
  } catch (error) {
    throw new CtxSyncError(`Invalid arguments: ${(error as Error).message}`, {
      code: "cli.args",
      exitCode: 2,
    });
  }
}

