const COMMON_OPTIONS = {
  root: { type: "string" },
  source: { type: "string" },
  profile: { type: "string", multiple: true },
  json: { type: "boolean" },
  github: { type: "boolean" },
  quiet: { type: "boolean" },
  "no-color": { type: "boolean" },
  help: { type: "boolean", short: "h" },
} as const;

function resolveColor(values: ArgValues): boolean {
  if (asBoolean(values, "no-color") || process.env["NO_COLOR"] !== undefined) {
    return false;
  }
  return process.stdout.isTTY === true;
}

function assertOutputMode(values: ArgValues): void {
  if (asBoolean(values, "json") && asBoolean(values, "github")) {
    throw new CtxSyncError(
      "--json and --github cannot be combined: both write to stdout.",
      { code: "cli.output-mode", exitCode: 2 },
    );
  }
}

/* -------------------------------------------------------------------------- */
/* Diagnostics / annotations                                                  */
/* -------------------------------------------------------------------------- */

function printDiagnostics(diagnostics: readonly Diagnostic[], quiet: boolean): void {
  for (const diagnostic of diagnostics) {
    if (quiet && diagnostic.severity === "warning") {
      continue;
    }
    const location =
      diagnostic.path === undefined
        ? ""
        : ` ${diagnostic.path}${diagnostic.line === undefined ? "" : `:${diagnostic.line}`}`;
    const prefix = diagnostic.severity === "error" ? "error" : "warning";
    writeErr(`${prefix}:${location} ${diagnostic.message} (${diagnostic.code})`);
  }
}

function emitBuildAnnotations(summary: BuildSummary): void {
  for (const diagnostic of summary.diagnostics) {
    writeOut(
      formatGithubAnnotation({
        kind: diagnostic.severity === "error" ? "error" : "warning",
        title: `${TOOL_NAME} ${diagnostic.code}`,
        message: diagnostic.message,
        ...(diagnostic.path === undefined ? {} : { file: diagnostic.path }),
        ...(diagnostic.line === undefined ? {} : { line: diagnostic.line }),
      }),
    );
  }

  if (summary.check && summary.drift) {
    for (const change of summary.changes) {
      if (change.status === "unchanged" || change.status === "blocked") {
        continue;
      }
      writeOut(
        formatGithubAnnotation({
          kind: "error",
          title: `${TOOL_NAME} stale output`,
          message:
            `Generated file is ${change.status}. Run \`${TOOL_NAME} build\` and commit the result.`,
          file: change.path,
        }),
      );
    }
  } else if (summary.ok) {
    writeOut(
      formatGithubAnnotation({
        kind: "notice",
        title: TOOL_NAME,
        message: `Build is up to date (${summary.blocks} ${plural(
          summary.blocks,
          "rule",
        )}, ${summary.profiles.join(", ")}).`,
      }),
    );
  }
}

function emitAuditAnnotations(report: AuditReport): void {
  for (const finding of report.findings) {
    writeOut(
      formatGithubAnnotation({
        kind: finding.severity === "critical" ? "error" : "warning",
        title: `${TOOL_NAME} ${finding.kind}`,
        message: `${finding.title}: ${finding.message}`,
        ...(finding.path === undefined ? {} : { file: finding.path }),
        ...(finding.line === undefined ? {} : { line: finding.line }),
        ...(finding.column === undefined ? {} : { column: finding.column }),
      }),
    );
  }

  for (const finding of report.secrets.findings) {
    writeOut(
      formatGithubAnnotation({
        kind: finding.severity === "critical" ? "error" : "warning",
        title: `${TOOL_NAME} secret`,
        message: `${finding.name} detected (${finding.ruleId}, fingerprint ${finding.fingerprint}). Rotate the credential if it is real.`,
        file: finding.path,
        line: finding.line,
        column: finding.column,
      }),
    );
  }

  if (report.severity === "ok") {
    writeOut(
      formatGithubAnnotation({
        kind: "notice",
        title: TOOL_NAME,
        message: `Audit passed: ${formatNumber(
          report.tokens.total.estimatedTokens,
        )} estimated source tokens, no secrets detected.`,
      }),
    );
  }
}

/* -------------------------------------------------------------------------- */
/* Build command                                                              */
/* -------------------------------------------------------------------------- */

function renderBuildHuman(
  summary: BuildSummary,
  palette: Palette,
  quiet: boolean,
): string {
  const lines: string[] = [];
  const mode = summary.check ? " --check" : summary.dryRun ? " --dry-run" : "";
  lines.push(palette.bold(`${TOOL_NAME} build${mode} v${VERSION}`));
  lines.push(
    palette.dim(
      `source ${summary.sourceDir} | ${summary.blocks} ${plural(
        summary.blocks,
        "rule",
      )} | profiles ${summary.profiles.join(", ")}`,
    ),
  );

  if (!quiet) {
    const width = 9;
    lines.push("");
    for (const change of summary.changes) {
      const label =
        change.status === "created"
          ? palette.green(padEnd(change.status, width))
          : change.status === "updated"
            ? palette.yellow(padEnd(change.status, width))
            : change.status === "removed"
              ? palette.red(padEnd(change.status, width))
              : change.status === "blocked"
                ? palette.red(padEnd(change.status, width))
                : palette.dim(padEnd(change.status, width));
      lines.push(
        `  ${label} ${change.path} ${palette.dim(
          `(${formatNumber(change.estimatedTokens)} est. tokens)`,
        )}`,
      );
    }
  }

  const created = summary.changes.filter((change) => change.status === "created").length;
  const updated = summary.changes.filter((change) => change.status === "updated").length;
  const removed = summary.changes.filter((change) => change.status === "removed").length;
  const blocked = summary.changes.filter((change) => change.status === "blocked").length;
  const unchanged = summary.changes.filter((change) => change.status === "unchanged").length;

  lines.push("");
  if (!summary.valid) {
    lines.push(palette.red("Build aborted: fix the source errors above."));
  } else if (summary.check) {
    if (summary.drift) {
      lines.push(
        palette.red(
          `Generated files are stale (${created} to create, ${updated} to update, ${removed} to remove).`,
        ),
      );
      lines.push(`Run \`${TOOL_NAME} build\` and commit the result.`);
    } else {
      lines.push(palette.green("All generated files are up to date."));
    }
  } else if (summary.dryRun) {
    lines.push(
      `Dry run: ${created} to create, ${updated} to update, ${removed} to remove, ${unchanged} unchanged${
        blocked > 0 ? `, ${blocked} blocked` : ""
      }.`,
    );
  } else if (!summary.drift) {
    lines.push(palette.green("Everything is already up to date."));
  } else {
    const wrote = created + updated;
    lines.push(
      palette.green(
        `Wrote ${wrote} ${plural(wrote, "file")}, removed ${removed}. ${unchanged} unchanged.`,
      ),
    );
  }

  return lines.join("\n");
}

async function runBuild(args: string[]): Promise<number> {
  const values = parseCommandArgs(args, {
    ...COMMON_OPTIONS,
    check: { type: "boolean" },
    "dry-run": { type: "boolean" },
    force: { type: "boolean" },
  });

  if (asBoolean(values, "help")) {
    writeOut(buildHelp());
    return 0;
  }
  assertOutputMode(values);

  const palette = createPalette(resolveColor(values));
  const quiet = asBoolean(values, "quiet");
  const json = asBoolean(values, "json");
  const github = asBoolean(values, "github");
  const check = asBoolean(values, "check");
  const dryRun = asBoolean(values, "dry-run");

  const summary = await syncProject({
    rootDir: path.resolve(asString(values, "root") ?? process.cwd()),
    ...(asString(values, "source") === undefined
      ? {}
      : { sourceDir: asString(values, "source") as string }),
    ...(parseProfiles(values) === undefined
      ? {}
      : { profiles: parseProfiles(values) as TargetProfile[] }),
    check,
    dryRun,
    force: asBoolean(values, "force"),
  });

  if (json) {
    writeOut(JSON.stringify(summary, null, 2));
  } else if (github) {
    emitBuildAnnotations(summary);
  } else {
    printDiagnostics(summary.diagnostics, quiet);
    writeOut(renderBuildHuman(summary, palette, quiet));
  }

  if (!summary.valid) {
    return 2;
  }
  if (check && summary.drift) {
    return 1;
  }
  return 0;
}

/* -------------------------------------------------------------------------- */
/* Audit command                                                              */
/* -------------------------------------------------------------------------- */

function renderAuditHuman(
  report: AuditReport,
  palette: Palette,
  quiet: boolean,
): string {
  const lines: string[] = [];
  lines.push(palette.bold(`${TOOL_NAME} audit v${VERSION}`));
  lines.push(
    palette.dim(
      `source ${report.sourceDir} | ${report.source.filesRead} ${plural(
        report.source.filesRead,
        "file",
      )} | ${report.source.blocks} ${plural(report.source.blocks, "rule")} | ${formatNumber(
        report.tokens.total.estimatedTokens,
      )} estimated source tokens`,
    ),
  );
  lines.push(
    palette.dim(
      `budget ${report.tokens.budget.maxPerProfile === 0 ? "off" : formatNumber(report.tokens.budget.maxPerProfile)}/profile, ${
        report.tokens.budget.maxPerBlock === 0
          ? "off"
          : formatNumber(report.tokens.budget.maxPerBlock)
      }/rule | estimator ${report.tokens.method}`,
    ),
  );

  if (!quiet) {
    lines.push("", palette.bold("Token usage"));
    if (report.tokens.blocks.length === 0) {
      lines.push("  No enabled rules.");
    } else {
      lines.push(palette.dim("  Rule                         tokens  source"));
      for (const block of report.tokens.blocks) {
        const tokens = severityPaint(
          palette,
          block.status,
          padStart(formatNumber(block.metrics.estimatedTokens), 8),
        );
        const suffix =
          block.status === "ok"
            ? ""
            : palette.dim(
                `  ${block.status === "critical" ? "critical" : "warning"} > ${formatNumber(
                  block.maxTokens,
                )}`,
              );
        lines.push(
          `  ${padEnd(block.blockId.slice(0, 26), 28)} ${tokens}  ${block.sourcePath}${suffix}`,
        );
      }
    }

    lines.push("", palette.bold("Compiled outputs"));
    for (const profile of report.tokens.profiles) {
      const location =
        profile.paths.length === 0
          ? "(no files)"
          : profile.paths.length === 1
            ? (profile.paths[0] ?? "")
            : `${profile.paths[0]} +${profile.paths.length - 1}`;
      const tokens = severityPaint(
        palette,
        profile.status,
        padStart(formatNumber(profile.metrics.estimatedTokens), 8),
      );
      lines.push(
        `  ${padEnd(profile.profile, 10)} ${tokens}  ${location} ${palette.dim(
          `(${profile.blockCount} ${plural(profile.blockCount, "rule")})`,
        )}`,
      );
    }
  }

  lines.push("", palette.bold("Secrets"));
  if (report.secrets.findings.length === 0) {
    lines.push(
      palette.green(
        `  No secrets detected in ${report.secrets.scannedFiles} scanned ${plural(
          report.secrets.scannedFiles,
          "file",
        )}.`,
      ),
    );
  } else {
    for (const finding of report.secrets.findings) {
      lines.push(
        `  ${severityPaint(palette, finding.severity, padEnd(finding.severity, 8))} ${finding.name} at ${finding.path}:${finding.line}:${finding.column}`,
      );
      lines.push(
        `  ${" ".repeat(8)} ${finding.description} Fingerprint ${finding.fingerprint}.`,
      );
    }
  }

  if (report.findings.length > 0) {
    lines.push("", palette.bold("Findings"));
    for (const finding of report.findings) {
      const location =
        finding.path === undefined
          ? ""
          : ` (${finding.path}${finding.line === undefined ? "" : `:${finding.line}`})`;
      lines.push(
        `  ${severityPaint(palette, finding.severity, padEnd(finding.severity, 8))} ${finding.title}${location}`,
      );
      lines.push(`  ${" ".repeat(8)} ${finding.message}`);
    }
  }

  const criticalCount =
    report.findings.filter((finding) => finding.severity === "critical").length +
    report.secrets.findings.filter((finding) => finding.severity === "critical").length;
  const warningCount =
    report.findings.filter((finding) => finding.severity === "warning").length +
    report.secrets.findings.filter((finding) => finding.severity === "warning").length;

  lines.push("", palette.bold("Result"));
  lines.push(
    `  ${severityPaint(palette, report.severity, report.severity.toUpperCase())} - ${criticalCount} critical, ${warningCount} ${plural(
      warningCount,
      "warning",
    )}, ${report.source.diagnostics.length} source ${plural(
      report.source.diagnostics.length,
      "diagnostic",
    )}.`,
  );

  const failed =
    report.failOn !== "never" &&
    report.severity !== "ok" &&
    SEVERITY_RANK[report.severity] >= (report.failOn === "critical" ? 2 : 1);
  lines.push(
    failed
      ? palette.red(`  Audit failed: severity meets --fail-on ${report.failOn}.`)
      : palette.green(`  Audit passed --fail-on ${report.failOn}.`),
  );

  return lines.join("\n");
}

async function runAudit(args: string[]): Promise<number> {
  const values = parseCommandArgs(args, {
    ...COMMON_OPTIONS,
    "fail-on": { type: "string" },
    "max-profile-tokens": { type: "string" },
    "max-block-tokens": { type: "string" },
  });

  if (asBoolean(values, "help")) {
    writeOut(auditHelp());
    return 0;
  }
  assertOutputMode(values);

  const palette = createPalette(resolveColor(values));
  const quiet = asBoolean(values, "quiet");
  const json = asBoolean(values, "json");
  const github = asBoolean(values, "github");
  const failOn = parseFailOn(values);
  const profiles = parseProfiles(values);
  const maxPerProfile = parseBudget(
    asString(values, "max-profile-tokens"),
    "--max-profile-tokens",
  );
  const maxPerBlock = parseBudget(
    asString(values, "max-block-tokens"),
    "--max-block-tokens",
  );

  const report = await auditProject({
    rootDir: path.resolve(asString(values, "root") ?? process.cwd()),
    ...(asString(values, "source") === undefined
      ? {}
      : { sourceDir: asString(values, "source") as string }),
    ...(profiles === undefined ? {} : { profiles }),
    ...(maxPerProfile === undefined ? {} : { maxPerProfile }),
    ...(maxPerBlock === undefined ? {} : { maxPerBlock }),
    failOn,
  });

  if (json) {
    writeOut(JSON.stringify(report, null, 2));
  } else if (github) {
    emitAuditAnnotations(report);
  } else {
    writeOut(renderAuditHuman(report, palette, quiet));
  }

  if (report.source.diagnostics.some((diagnostic) => diagnostic.severity === "error")) {
    return 2;
  }
  if (failOn === "never" || report.severity === "ok") {
    return 0;
  }
  const threshold = failOn === "critical" ? 2 : 1;
  return SEVERITY_RANK[report.severity] >= threshold ? 1 : 0;
}

/* -------------------------------------------------------------------------- */
/* Entry point                                                                */
/* -------------------------------------------------------------------------- */

async function dispatch(argv: string[]): Promise<number> {
  if (argv.length === 0) {
    writeOut(mainHelp());
    return 0;
  }

  const first = argv[0] ?? "";
  if (first === "--version" || first === "-v") {
    writeOut(`${TOOL_NAME} ${VERSION}`);
    return 0;
  }
  if (first === "--help" || first === "-h" || first === "help") {
    writeOut(mainHelp());
    return 0;
  }

  if (first === "build") {
    return runBuild(argv.slice(1));
  }
  if (first === "audit") {
    return runAudit(argv.slice(1));
  }

  writeErr(`error: unknown command "${first}".`);
  writeErr(`Run \`${TOOL_NAME} --help\` for usage.`);
  return 2;
}

export async function main(argv: string[] = process.argv.slice(2)): Promise<number> {
  try {
    return await dispatch(argv);
  } catch (error) {
    if (error instanceof CtxSyncError) {
      writeErr(`error: ${error.message}`);
      return error.exitCode;
    }
    const message = error instanceof Error ? error.message : String(error);
    writeErr(`error: unexpected failure: ${message}`);
    if (process.env["CTX_SYNC_DEBUG"] !== undefined && error instanceof Error) {
      writeErr(error.stack ?? message);
    }
    return 3;
  }
}

function executedDirectly(): boolean {
  const entry = process.argv[1];
  if (entry === undefined) {
    return false;
  }
  try {
    return realpathSync(entry) === realpathSync(new URL(import.meta.url));
  } catch {
    return pathToFileURL(path.resolve(entry)).href === import.meta.url;
  }
}

if (executedDirectly()) {
  void main().then((code) => {
    process.exitCode = code;
  });
}
