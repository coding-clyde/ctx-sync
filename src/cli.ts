interface Palette {
  bold(value: string): string;
  dim(value: string): string;
  red(value: string): string;
  yellow(value: string): string;
  green(value: string): string;
  cyan(value: string): string;
}

function createPalette(enabled: boolean): Palette {
  const wrap = (code: number) => (value: string) =>
    enabled ? `\u001B[${code}m${value}\u001B[0m` : value;
  return {
    bold: wrap(1),
    dim: wrap(2),
    red: wrap(31),
    yellow: wrap(33),
    green: wrap(32),
    cyan: wrap(36),
  };
}

function severityPaint(
  palette: Palette,
  severity: Severity,
  value: string,
): string {
  if (severity === "critical") {
    return palette.red(value);
  }
  if (severity === "warning") {
    return palette.yellow(value);
  }
  return palette.green(value);
}

function writeOut(value: string): void {
  process.stdout.write(value.endsWith("\n") ? value : `${value}\n`);
}

function writeErr(value: string): void {
  process.stderr.write(value.endsWith("\n") ? value : `${value}\n`);
}

