const FENCE = /^ {0,3}(`{3,}|~{3,})/;
const ATX_HEADING = /^ {0,3}(#{1,6})(?=[ \t]|$)/;

/** Apply `visit` to every line that is not inside a fenced code block. */
function mapOutsideFences(
  markdown: string,
  visit: (line: string) => string,
): string {
  let fence: string | null = null;
  return markdown
    .split("\n")
    .map((line) => {
      const match = FENCE.exec(line);
      if (match !== null) {
        const marker = match[1] as string;
        if (fence === null) {
          fence = marker;
        } else if (marker[0] === fence[0] && marker.length >= fence.length) {
          fence = null;
        }
        return line;
      }
      return fence === null ? visit(line) : line;
    })
    .join("\n");
}

/**
 * Shift ATX headings so the shallowest one in `markdown` becomes
 * `minLevel`. Headings that are already deep enough, and anything inside a
 * fenced code block, are left untouched. Levels are capped at 6.
 */
export function demoteHeadings(markdown: string, minLevel: number): string {
  let shallowest = 7;
  mapOutsideFences(markdown, (line) => {
    const match = ATX_HEADING.exec(line);
    if (match !== null) {
      shallowest = Math.min(shallowest, (match[1] as string).length);
    }
    return line;
  });
  const shift = shallowest === 7 ? 0 : Math.max(0, minLevel - shallowest);
  if (shift === 0) {
    return markdown;
  }
  return mapOutsideFences(markdown, (line) => {
    const match = ATX_HEADING.exec(line);
    if (match === null) {
      return line;
    }
    const level = (match[1] as string).length;
    const next = "#".repeat(Math.min(6, level + shift));
    return `${next}${line.slice(match[0].length)}`;
  });
}

/** GitHub-style heading anchor, unique within one document. */
export function createSlugger(): (heading: string) => string {
  const seen = new Map<string, number>();
  return (heading) => {
    const base =
      oneLine(heading)
        .toLowerCase()
        .replace(/[^\p{L}\p{N}\s_-]/gu, "")
        .replace(/\s/g, "-") || "section";
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    return count === 0 ? base : `${base}-${count}`;
  };
}

/** Section body with headings nested under its `##` title. */
export function sectionBody(block: RuleBlock): string {
  return block.body.length > 0 ? demoteHeadings(block.body, 3) : "";
}

export interface DocumentOptions {
  /** The single H1 of the document. */
  title: string;
  /** Emit a linked table of contents before the sections. */
  index?: boolean;
  /** Emit `<!-- source: ... -->` under each section heading. */
  sourceComments?: boolean;
}

/**
 * Header + H1 + optional index + one `##` section per block, with block
 * headings nested below it so the outline is always well-formed.
 */
export function buildMarkdownDocument(
  profile: TargetProfile,
  blocks: readonly RuleBlock[],
  config: ResolvedConfig,
  options: DocumentOptions,
): string {
  const selected = blocksForProfile(blocks, profile);
  const parts: string[] = [
    generatedHeader(profile, config.sourceDirRelative),
    "",
    `# ${options.title}`,
  ];

  if (options.index === true && selected.length > 0) {
    const slug = createSlugger();
    parts.push("", "## Index", "");
    for (const block of selected) {
      const title = oneLine(block.title);
      // Only an explicit frontmatter description: the derived one is just the
      // first sentence of the body and reads badly out of context.
      const explicit = block.frontmatter.description;
      const description = typeof explicit === "string" ? oneLine(explicit) : "";
      const summary =
        description.length > 0 && description !== title
          ? `: ${truncate(description, 140)}`
          : "";
      parts.push(`- [${title}](#${slug(title)})${summary}`);
    }
  }

  for (const block of selected) {
    parts.push("", `## ${oneLine(block.title)}`);
    if (options.sourceComments === true) {
      parts.push(`<!-- source: ${escapeHtmlComment(block.sourcePath)} -->`);
    }
    const body = sectionBody(block);
    if (body.length > 0) {
      parts.push("", body);
    }
  }

  return `${parts.join("\n").replace(/\n+$/u, "")}\n`;
}

/* -------------------------------------------------------------------------- */
/* Adapter factory                                                            */
/* -------------------------------------------------------------------------- */

export interface SingleFileAdapterSpec extends DocumentOptions {
  id: TargetProfile;
  label: string;
  defaultOutput: string;
  order?: number;
}

/** Factory for adapters that compile every rule into one Markdown file. */
export function createSingleFileAdapter(spec: SingleFileAdapterSpec): Adapter {
  const adapter: Adapter = {
    id: spec.id,
    label: spec.label,
    kind: "single-file",
    defaultOutput: spec.defaultOutput,
    ...(spec.order === undefined ? {} : { order: spec.order }),
    render(blocks, context): GeneratedFile[] {
      const selected = blocksForProfile(blocks, spec.id);
      return [
        {
          profile: spec.id,
          path: profileOutput(context.config, adapter),
          content: buildMarkdownDocument(spec.id, blocks, context.config, spec),
          blockIds: selected.map((block) => block.id),
        },
      ];
    },
  };
  return adapter;
}
