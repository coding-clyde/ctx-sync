import type {
  Adapter,
  GeneratedFile,
  ResolvedConfig,
  RuleBlock,
  TargetProfile,
} from "../types.js";
import { TARGET_PROFILE_DEFAULT_OUTPUTS, TARGET_PROFILE_LABELS } from "../types.js";
import { oneLine } from "../utils/format.js";
import { VERSION } from "../version.js";

/** Stable token used to identify files owned by ctx-sync. */
export const GENERATED_MARKER = "ctx-sync:generated";

/** Only files carrying this marker may be overwritten or deleted. */
export function hasGeneratedMarker(content: string): boolean {
  return /<!--\s*ctx-sync:generated\b/.test(content.slice(0, 2_000));
}

function escapeHtmlComment(value: string): string {
  return value.replaceAll("--", "- -").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
}

export function generatedHeader(
  profile: TargetProfile,
  sourceDirRelative: string,
): string {
  const source = escapeHtmlComment(sourceDirRelative.length > 0 ? sourceDirRelative : ".");
  return [
    `<!-- ${GENERATED_MARKER} profile="${profile}" version="${VERSION}" -->`,
    `<!-- Generated from ${source} by ctx-sync. Do not edit this file manually. -->`,
  ].join("\n");
}

export function profileOutput(
  config: ResolvedConfig,
  profile: TargetProfile,
): string {
  const resolved = config.profiles.find((entry) => entry.profile === profile);
  return (resolved?.output ?? TARGET_PROFILE_DEFAULT_OUTPUTS[profile])
    .replaceAll("\\", "/")
    .replace(/\/+/g, "/")
    .replace(/\/$/, "");
}

/**
 * Enabled blocks for one profile, in render order. Source order is already
 * deterministic; sorting again keeps adapters correct when used directly.
 */
export function blocksForProfile(
  blocks: readonly RuleBlock[],
  profile: TargetProfile,
): RuleBlock[] {
  return blocks
    .filter((block) => block.enabled && block.targets.includes(profile))
    .sort(
      (left, right) =>
        right.priority - left.priority ||
        left.order - right.order ||
        left.id.localeCompare(right.id, "en"),
    );
}

export function joinPosix(...parts: string[]): string {
  return parts
    .map((part) => part.replaceAll("\\", "/").replace(/^\/+|\/+$/g, ""))
    .filter((part) => part.length > 0)
    .join("/");
}

export function yamlString(value: string): string {
  // JSON string escapes are valid in YAML double-quoted scalars.
  return JSON.stringify(value);
}

export function buildSingleFileDocument(
  profile: TargetProfile,
  blocks: readonly RuleBlock[],
  config: ResolvedConfig,
): string {
  const selected = blocksForProfile(blocks, profile);
  const parts: string[] = [
    generatedHeader(profile, config.sourceDirRelative),
    "",
    "# Repository context",
  ];

  for (const block of selected) {
    parts.push("", `## ${oneLine(block.title)}`);
    if (block.body.length > 0) {
      parts.push("", block.body);
    }
  }

  return `${parts.join("\n").replace(/\n+$/u, "")}\n`;
}

/** Factory for adapters that compile every rule into one Markdown file. */
export function createSingleFileAdapter(profile: TargetProfile): Adapter {
  return {
    id: profile,
    label: TARGET_PROFILE_LABELS[profile],
    kind: "single-file",
    defaultOutput: TARGET_PROFILE_DEFAULT_OUTPUTS[profile],
    render(blocks, context): GeneratedFile[] {
      const selected = blocksForProfile(blocks, profile);
      return [
        {
          profile,
          path: profileOutput(context.config, profile),
          content: buildSingleFileDocument(profile, blocks, context.config),
          blockIds: selected.map((block) => block.id),
        },
      ];
    },
  };
}
